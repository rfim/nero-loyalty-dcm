#!/usr/bin/env python3
"""Generator: ingestion/contract/ (meta.yaml + datasets/*.yaml) -> generated
DCM SQL + reference SQL, and (with --seed) loads the PII column registry
and the lineage map with data.

NERO_DB is split into numbered schemas by pipeline stage. sources/definitions/
mirrors this: one folder per DCM-managed schema (see sources/definitions/
README.md for the full breakdown, including what's deliberately NOT DCM --
01_BRONZE is dbt-owned, 02_CONTROL/04_METADATA are plain SQL via
account_setup/).
  00_STAGING      typed, unvalidated landing (STAGING_<DATASET>,
                  STAGING_BATCH_MANIFESTS, LANDING_STAGE) -- was 00_BRONZE
  01_BRONZE       contract-filtered tables (BRONZE_*) -- dbt-owned, built by
                  analytics/models/bronze/, not generated here. Was
                  01_SILVER/VALIDATED_* before the Staging/Bronze/Silver
                  rename (see analytics/README.md for the full mapping).
  02_CONTROL      CONTRACT_REJECTIONS view (staged vs. published keys per
                  dataset) -- was: contract registry, audit, release
                  pointer, PROCESS_BATCH/RUN_PENDING, all retired.
  03_LINEAGE      pipeline stage/dependency documentation
  04_METADATA     DATASET_FRESHNESS view, PIPELINE_WATERMARKS and
                  PIPELINE_RUN_LOG tables (written by dbt's on-run-end
                  hooks) -- see account_setup/dbt_pipeline_metadata.sql
  05_PII_CONTROL  PII column registry, sourced from the contract's pii tags

Emits:
  - sources/definitions/00_staging/raw.sql        (DCM-managed, deployed --
    STAGING_<DATASET> + STAGING_BATCH_MANIFESTS)
  - sources/definitions/03_lineage/lineage.sql     (DCM-managed, deployed —
    schema only; rows loaded by --seed, since DCM manages schema not data)
  - sources/definitions/05_pii_control/pii_registry.sql (DCM-managed,
    deployed — schema only; rows loaded by --seed)
  - ingestion/reference/s3.sql       (NOT under sources/definitions, so DCM
    ignores it — real SQL, but UNVERIFIED: no live AWS credentials here)
  - ingestion/reference/masking.sql  (real SQL for PII masking + the
    column-attach step, also UNVERIFIED: this Snowflake account's edition
    doesn't support masking policies at all, confirmed independent of DCM)
  - ingestion/generated/google_sheets_procedure.sql (real SQL, NOT
    DCM-managed -- a stored procedure plus its task and grants, none of
    them DEFINE-able DCM objects. Embeds the URLs from
    ingestion.sources[google_sheets_feed].google_sheets.urls. Deploy
    AFTER account_setup/google_sheets_ingest.sql, which creates the
    external access integration this procedure requires at CREATE time.)

ingestion.sources is a list: every mechanism that can land data into
staging is declared in the contract, whether or not it is currently
deployed (status: deployed | unverified | temporary). Only the
type=internal_stage source's landing.type=typed combination is deployed
and tested end-to-end here; other source types generate what they can
(google_sheets, s3) or are documentation-only (synthetic). Rejects unknown
keys at every level so a typo in the contract fails the build instead of
silently doing nothing.

Usage:
    python ingestion/build.py                              # generate only
    python ingestion/build.py --seed -c <snow_connection>   # generate + seed
"""
