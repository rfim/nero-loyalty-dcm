def seed_pii_registry(connection, doc):
    """Always reflects the current contract exactly — replace-all rather
    than additive, unlike the contract table itself."""
    rows = []
    for ds_name, ds in doc["datasets"].items():
        table = f"BRONZE_{ds_name.upper()}"
        for col_name, col in ds["columns"].items():
            if col.get("pii"):
                pii_kind = col.get("pii_kind", "identifier")
                policy = f"MASK_{pii_kind.upper()}_{col['type'].upper()}"
                rows.append((table, col_name.upper(), ds_name, pii_kind, policy))

    values_sql = ",\n        ".join(
        f"('{t}', '{c}', '{d}', '{p}', '{pol}', FALSE)" for t, c, d, p, pol in rows
    )
    sql = f"""
    DELETE FROM {PII_CONTROL}.PII_COLUMN_REGISTRY;
    INSERT INTO {PII_CONTROL}.PII_COLUMN_REGISTRY
        (TABLE_NAME, COLUMN_NAME, DATASET_NAME, PII_KIND, MASKING_POLICY_NAME, MASKING_ENFORCED)
    VALUES
        {values_sql};
    """
    subprocess.run(["snow", "sql", "-c", connection, "-q", sql], check=True)
    print(f"Seeded {len(rows)} PII column registry rows")


def seed_lineage(doc):
    """Static-ish documentation rows: staging -> bronze -> silver chain per
    dataset (all 3 now dbt-owned except staging's landing tables), plus
    gold/marts downstream. Replace-all, same as the PII registry — this
    always reflects the current contract + known dbt layer, not an
    append-only history."""
    rows = [
        ("NERO_DB", '00_STAGING', "STAGING_BATCH_MANIFESTS", "staging", None,
         "One row per submitted batch: contract pin + per-dataset row_count. Audit trail only, no reader."),
    ]
    for ds_name in doc["datasets"]:
        upper = ds_name.upper()
        rows += [
            ("NERO_DB", '00_STAGING', f"STAGING_{upper}", "staging",
             "NERO_DB.00_STAGING.STAGING_BATCH_MANIFESTS",
             f"Typed, unvalidated landing for {ds_name}. One row per record, real columns, no JSON."),
            ("NERO_DB", '01_BRONZE', f"BRONZE_{upper}", "bronze",
             f"NERO_DB.00_STAGING.STAGING_{upper}",
             f"Contract-filtered {ds_name} (dbt model, plain SQL filtering + tests -- see analytics/models/bronze/)."),
            ("NERO_ANALYTICS", '00_SILVER', f"SILVER_{upper}", "dbt_silver",
             f"NERO_DB.01_BRONZE.BRONZE_{upper}",
             f"dbt silver view over BRONZE_{upper} -- light transform (timezone, renames), SCD lives here too (see 01_SNAPSHOTS for customer SCD2)."),
        ]
    rows += [
        ("NERO_ANALYTICS", '02_GOLD', "DIM_* / FACT_*", "dbt_gold",
         "NERO_ANALYTICS.00_SILVER.SILVER_*",
         "Kimball dimensions/facts built from silver (+ 01_SNAPSHOTS for customer SCD2)."),
        ("NERO_ANALYTICS", '03_MART_MARKETING', "MART_*", "dbt_mart",
         "NERO_ANALYTICS.02_GOLD.DIM_*/FACT_*",
         "Marketing reporting marts."),
        ("NERO_ANALYTICS", '04_MART_OPERATIONS', "MART_*", "dbt_mart",
         "NERO_ANALYTICS.02_GOLD.DIM_*/FACT_*",
         "Operations reporting marts."),
    ]

    def esc(s):
        return s.replace("'", "''") if s else s

    values_sql = ",\n        ".join(
        "('{}', '{}', '{}', '{}', {}, '{}')".format(
            db, schema, obj, stage,
            f"'{esc(upstream)}'" if upstream else "NULL",
            esc(desc),
        )
        for db, schema, obj, stage, upstream, desc in rows
    )
    return f"""
    DELETE FROM {LINEAGE}.PIPELINE_STAGE_MAP;
    INSERT INTO {LINEAGE}.PIPELINE_STAGE_MAP
        (DATABASE_NAME, SCHEMA_NAME, OBJECT_NAME, STAGE, UPSTREAM_OBJECT, DESCRIPTION)
    VALUES
        {values_sql};
    """


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--seed", action="store_true",
                         help="also load the contract, PII registry, and lineage map with data")
    parser.add_argument("-c", "--connection", help="snow CLI connection name (required with --seed)")
    args = parser.parse_args()
    if args.seed and not args.connection:
        sys.exit("build.py: --seed requires -c/--connection")

    doc, contract_hash = load_contract()

    definitions_dir = ROOT / "sources" / "definitions"
    reference_dir = ROOT / "ingestion" / "reference"
    generated_dir = ROOT / "ingestion" / "generated"
    (definitions_dir / "00_staging").mkdir(parents=True, exist_ok=True)
    (definitions_dir / "03_lineage").mkdir(parents=True, exist_ok=True)
    (definitions_dir / "05_pii_control").mkdir(parents=True, exist_ok=True)
    reference_dir.mkdir(parents=True, exist_ok=True)
    generated_dir.mkdir(parents=True, exist_ok=True)

    (definitions_dir / "00_staging" / "raw.sql").write_text(gen_raw_landing(doc))
    (definitions_dir / "03_lineage" / "lineage.sql").write_text(gen_lineage_schema(doc))
    (definitions_dir / "05_pii_control" / "pii_registry.sql").write_text(gen_pii_registry_schema(doc))

    masking_sql = gen_masking_reference(doc)
    masking_path = reference_dir / "masking.sql"
    if masking_sql:
        masking_path.write_text(masking_sql)
    elif masking_path.exists():
        masking_path.unlink()

    s3_sql = gen_s3_reference(doc)
    s3_path = reference_dir / "s3.sql"
    if s3_sql:
        s3_path.write_text(s3_sql)
    elif s3_path.exists():
        s3_path.unlink()

    gs_sql = gen_google_sheets_procedure(doc)
    gs_path = generated_dir / "google_sheets_procedure.sql"
    if gs_sql:
        gs_path.write_text(gs_sql)
    elif gs_path.exists():
        gs_path.unlink()

    print(f"Built from ingestion/contract/ (contract v{doc['version']}, hash={contract_hash})")
    print("Generated (DCM-managed, deployed):")
    print("  sources/definitions/00_staging/raw.sql")
    print("  sources/definitions/03_lineage/lineage.sql")
    print("  sources/definitions/05_pii_control/pii_registry.sql")
    print("Generated (reference only, NOT deployed by DCM):")
    if s3_sql:
        print("  ingestion/reference/s3.sql (unverified — no live AWS credentials)")
    if masking_sql:
        print("  ingestion/reference/masking.sql (unverified — account edition lacks masking policy support)")
    if gs_sql:
        print("  ingestion/generated/google_sheets_procedure.sql (deployed — apply after account_setup/google_sheets_ingest.sql)")

    if args.seed:
        seed_pii_registry(args.connection, doc)
        subprocess.run(["snow", "sql", "-c", args.connection, "-q", seed_lineage(doc)], check=True)
        print("Seeded lineage map")


if __name__ == "__main__":
    main()
