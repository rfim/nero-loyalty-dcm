def find_source(doc, source_type):
    """First ingestion.sources[] entry of the given type, or None."""
    for src in doc["ingestion"]["sources"]:
        if src["type"] == source_type:
            return src
    return None

SQL_TYPE_MAP = {
    "integer": "NUMBER",
    "decimal": None,  # needs precision/scale, handled specially
    "string": None,   # needs max_length, handled specially
    "date": "DATE",
    "timestamp_tz": "TIMESTAMP_TZ",
}


def sql_column_type(name, spec, path):
    t = spec["type"]
    if t == "string":
        max_len = spec.get("max_length", 16777216)
        return f"VARCHAR({max_len})"
    if t == "decimal":
        precision = spec.get("precision", 38)
        scale = spec.get("scale", 0)
        return f"NUMBER({precision},{scale})"
    if t in SQL_TYPE_MAP:
        return SQL_TYPE_MAP[t]
    sys.exit(f"build.py: unsupported column type '{t}' at {path}")


def gen_raw_landing(doc):
    landing = doc["ingestion"]["landing"]
    source = find_source(doc, "internal_stage")
    lines = [
        "-- =============================================================================",
        "-- GENERATED by ingestion/build.py from ingestion/contract/ — do not hand-edit.",
        "-- Edit the contract and rerun `python ingestion/build.py` instead.",
        "-- =============================================================================",
        "",
    ]
    if source is not None:
        lines += [
            f"DEFINE STAGE {STAGING}.LANDING_STAGE",
            "    COMMENT = 'Credential-free internal stage for manual/CI batch uploads (typed per-dataset CSVs, one file per dataset per batch).';",
            "",
        ]
    else:
        sys.exit("build.py: no ingestion.sources[] entry of type 'internal_stage' — "
                  "see ingestion/reference/s3.sql for the (unverified) s3 route.")

    if landing["type"] == "typed":
        # One typed table per contract dataset -- readable by design (real
        # columns, not a JSON blob), landed directly by each adapter or via
        # COPY INTO from a per-dataset staged CSV. Columns are nullable
        # regardless of the contract's own nullable flag: staging's job is
        # to preserve whatever arrived, including invalid rows, so
        # downstream contract filtering (analytics/models/bronze/) can give
        # a precise "this row is missing a required column" signal instead
        # of the INSERT itself opaquely failing. NOT NULL is enforced
        # downstream, on BRONZE_<DATASET> (dbt-owned, not generated here).
        for ds_name, ds in doc["datasets"].items():
            table = f"{landing['dataset_table_prefix']}{ds_name.upper()}"
            col_lines = []
            for col_name, col in ds["columns"].items():
                sql_type = sql_column_type(col_name, col, f"datasets.{ds_name}.columns.{col_name}")
                col_lines.append(f"    {col_name.upper():<20} {sql_type},")
            col_lines += [
                "    BATCH_ID             VARCHAR(200) NOT NULL,",
                "    FILE_ROW_NUMBER      NUMBER       NOT NULL,",
                "    INGESTED_AT          TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()",
            ]
            lines.append(f"DEFINE TABLE {table} (")
            lines += col_lines
            lines.append(")")
            contract_version = doc["version"]
            lines.append(f"COMMENT = 'Typed staging landing for {ds_name}, one row per record, unvalidated. Batches identified by BATCH_ID; FILE_ROW_NUMBER is per-batch position. Generated from contract v{contract_version}.';")
            lines.append("")

        lines += [
            f"DEFINE TABLE {landing['manifest_table_name']} (",
            "    BATCH_ID          VARCHAR(200)  NOT NULL,",
            "    CONTRACT_ID       VARCHAR(200)  NOT NULL,",
            "    CONTRACT_VERSION  NUMBER        NOT NULL,",
            "    SOURCE_SYSTEM     VARCHAR(200),",
            "    CAPTURED_AT       TIMESTAMP_TZ  NOT NULL,",
            "    DATASETS          VARIANT       NOT NULL,",
            "    INGESTED_AT       TIMESTAMP_TZ  DEFAULT CURRENT_TIMESTAMP(),",
            "    PRIMARY KEY (BATCH_ID)",
            ")",
            "COMMENT = 'One row per submitted batch: which contract version it targets, and per-dataset {row_count} in DATASETS. Audit trail only -- dbt reads STAGING_<DATASET> directly and does not consult this table.';",
        ]
    elif landing["type"] == "iceberg":
        iceberg = landing["iceberg"]
        lines += [
            f"DEFINE ICEBERG TABLE {landing['manifest_table_name']} (",
            "    PAYLOAD          VARCHAR       NOT NULL,",
            "    FILE_NAME        VARCHAR,",
            "    FILE_ROW_NUMBER  NUMBER,",
            "    FILE_CONTENT_KEY VARCHAR,",
            "    INGESTED_AT      TIMESTAMP_TZ",
            ")",
            f"CATALOG = 'SNOWFLAKE'",
            f"EXTERNAL_VOLUME = '{iceberg['external_volume']}'",
            f"BASE_LOCATION = '{iceberg['base_location']}';",
        ]
    else:
        sys.exit(f"build.py: unknown landing.type '{landing['type']}'")

    return "\n".join(lines) + "\n"


