GRANT SELECT ON VIEW NERO_DB."04_METADATA".DATASET_FRESHNESS TO ROLE NERO_POWERBI_ROLE;

GRANT USAGE ON DATABASE NERO_GOVERNANCE TO ROLE NERO_POWERBI_ROLE;
GRANT USAGE ON SCHEMA NERO_GOVERNANCE.REPORTING TO ROLE NERO_POWERBI_ROLE;
